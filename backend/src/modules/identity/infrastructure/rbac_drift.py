"""RBAC drift: read the live database, compare against the code baseline, report.

Also generates the literal payload for the seed migration, so those literals are
never hand-typed.

Two distinct drifts, one shared source of truth:

  * BUILD-TIME  — code baseline vs the literals frozen into the seed migration.
                  Guarded by a test, so changing the enum/roles/mapping without
                  regenerating the migration fails CI.
  * RUN-TIME    — code baseline vs what a database actually holds.
                  Reported by this module's command.

Run as its own process, matching the repository's existing worker convention
(`python -m src.shared_kernel.infrastructure.outbox.runner`):

    python -m src.modules.identity.infrastructure.rbac_drift          # report
    python -m src.modules.identity.infrastructure.rbac_drift --emit   # literals

Exit code is 0 when clean and 1 when drift is detected, so it can gate a
deployment without any extra tooling.
"""

from __future__ import annotations

import asyncio
import sys

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession, async_sessionmaker

from src.modules.identity.application.rbac_baseline import (
    ActualRbacState,
    RbacDrift,
    compute_drift,
    expected_state,
)
from src.shared_kernel.infrastructure.database import SessionFactory

# Narrow SQL, joined on stable CODES — never on surrogate ids (ADR-0011 §12).
_ROLE_CODES = text("SELECT code FROM roles")
_PERMISSION_CODES = text("SELECT code FROM permissions")
_GRANTS = text(
    """
    SELECT r.code AS role_code, p.code AS permission_code
      FROM role_permissions rp
      JOIN roles r       ON r.id = rp.role_id
      JOIN permissions p ON p.id = rp.permission_id
    """
)


class SqlRbacStateReader:
    """Reads the live RBAC state. Read-only; never writes."""

    def __init__(self, session: AsyncSession) -> None:
        self._s = session

    async def read(self) -> ActualRbacState:
        roles = await self._s.execute(_ROLE_CODES)
        permissions = await self._s.execute(_PERMISSION_CODES)
        grants = await self._s.execute(_GRANTS)
        return ActualRbacState(
            role_codes=frozenset(r[0] for r in roles),
            permission_codes=frozenset(r[0] for r in permissions),
            grants=frozenset((g[0], g[1]) for g in grants),
        )


async def check_drift(
    session_factory: async_sessionmaker[AsyncSession] = SessionFactory,
) -> RbacDrift:
    async with session_factory() as session:
        actual = await SqlRbacStateReader(session).read()
    return compute_drift(expected_state(), actual)


# --- migration literal generation ------------------------------------------
def emit_seed_literals() -> str:
    """Render the baseline as Python literals for pasting into a migration.

    Deterministic: `expected_state()` is fully sorted, so the same source always
    produces byte-identical output. Migrations must never import the live enum
    (ADR-0011 §12) — an old migration has to keep reproducing history even after
    the enum moves on — so this generator writes frozen literals instead.
    """
    state = expected_state()
    lines = [f"# Generated by: python -m {__name__} --emit",
             f"# Baseline fingerprint: {state.fingerprint()}",
             "",
             "ROLES = ("]
    lines += [f'    ({c!r}, {n!r}, {s}),' for c, n, s in state.roles]
    lines += [")", "", "PERMISSIONS = ("]
    lines += [f'    ({c!r}, {d!r}),' for c, d in state.permissions]
    lines += [")", "", "GRANTS = ("]
    lines += [f'    ({r!r}, {p!r}),' for r, p in state.grants]
    lines += [")"]
    return "\n".join(lines)


def _main() -> int:
    if "--emit" in sys.argv:
        print(emit_seed_literals())
        return 0
    drift = asyncio.run(check_drift())
    print(drift.render())
    return 0 if drift.is_clean else 1


if __name__ == "__main__":  # pragma: no cover - process entrypoint
    raise SystemExit(_main())
